"""Disagreement exhibits -- concrete cases where the LENIENT (mem0) judge says CORRECT and the
STRICT judge says WRONG on the SAME Mem0 answer: the actual question, the gold, Mem0's answer,
and both judges' one-line reasoning.

HISTORICAL. This script produced the earlier 922-case dump, which counted control-slice and
repeat duplicates. The committed artifact of record, experiments/hardening/disagreement_exhibits.{json,md}
(863 cases, per-conversation B_ verdicts only; counted by scripts/count_disagreements.py), supersedes it
and is NOT regenerated by this script. To avoid clobbering it, this script now writes
disagreement_exhibits_legacy.{json,md}. Not part of REPRODUCING.md.
"""
import json
from pathlib import Path

PAPER = Path(__file__).resolve().parents[1]
V = PAPER / "experiments/hardening/verdicts"
KIT = PAPER / "kit"


def answers_for(tag: str) -> dict:
    """qid -> {question, gold, answer, category} for a verdict tag (A_* = q8, B_convN_* = OSS)."""
    if tag.startswith("A_"):
        recs = json.loads((KIT / "data/answers_mem0_conv26.json").read_text(encoding="utf-8"))
    else:  # B_convN
        conv = tag.split("_")[1]
        recs = json.loads((KIT / f"data/mem0_oss_answers/{conv}.json").read_text(encoding="utf-8"))
    return {str(r["qid"]): r for r in recs}


def load_verdict(name: str) -> dict:
    p = V / f"{name}.json"
    if not p.exists():
        return {}
    return {str(r["qid"]): r for r in json.loads(p.read_text(encoding="utf-8"))}


def collect() -> list:
    cases = []
    # q8 (rep0) + each OSS conversation
    sets = [("A", "A_mem0_rep0", "A_strict_rep0")]
    for cp in sorted((KIT / "data/mem0_oss_answers").glob("conv*.json")):
        conv = cp.stem
        sets.append((f"B_{conv}", f"B_{conv}_mem0", f"B_{conv}_strict"))
    for src, mem0_name, strict_name in sets:
        mem0, strict = load_verdict(mem0_name), load_verdict(strict_name)
        if not mem0 or not strict:
            continue
        ans = answers_for(mem0_name)
        for qid, mv in mem0.items():
            sv = strict.get(qid)
            a = ans.get(qid)
            if not sv or not a:
                continue
            if mv.get("score") == 1.0 and sv.get("score") == 0.0:
                cases.append({
                    "source": src, "qid": qid, "category": a.get("category"),
                    "question": a["question"], "gold": a["gold"], "mem0_answer": a["answer"],
                    "mem0_reasoning": mv.get("reasoning", ""), "strict_reasoning": sv.get("reasoning", ""),
                })
    return cases


def rank(cases: list) -> list:
    # most damning first: temporal/date cases, then short wrong-looking answers.
    def key(c):
        cat = (c.get("category") or "").lower()
        temporal = 0 if ("temporal" in cat or "date" in cat) else 1
        return (temporal, len(str(c["mem0_answer"])))
    return sorted(cases, key=key)


def main() -> None:
    cases = rank(collect())
    (PAPER / "experiments/hardening/disagreement_exhibits_legacy.json").write_text(json.dumps(cases, indent=1), encoding="utf-8")
    lines = [f"# Disagreement exhibits -- lenient judge says CORRECT, strict says WRONG ({len(cases)} cases)\n"]
    lines.append("Same Mem0 answer, same gold. Only the grading prompt differs.\n")
    for i, c in enumerate(cases[:25], 1):
        lines += [
            f"## {i}. [{c['category']}] {c['source']} q{c['qid']}",
            f"- **Q:** {c['question']}",
            f"- **Gold:** {c['gold']}",
            f"- **Mem0's answer:** {c['mem0_answer']}",
            f"- **mem0 judge (CORRECT):** {c['mem0_reasoning']}",
            f"- **strict judge (WRONG):** {c['strict_reasoning']}\n",
        ]
    (PAPER / "experiments/hardening/disagreement_exhibits_legacy.md").write_text("\n".join(lines), encoding="utf-8")
    by_cat = {}
    for c in cases:
        by_cat[c["category"]] = by_cat.get(c["category"], 0) + 1
    print(f"hall of shame: {len(cases)} mem0=CORRECT/strict=WRONG cases  by category: {by_cat}")


if __name__ == "__main__":
    main()
